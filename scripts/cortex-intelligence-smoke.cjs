/* Run after cortex-smoke and cortex-extension-smoke against the disposable preview. */
const { chromium } = require("playwright");
const { expect } = require("playwright/test");
const fs = require("node:fs");
let browser;
(async () => {
  if (process.env.NODE_ENV === "production") throw Error("Disposable preview only");
  const state = JSON.parse(fs.readFileSync(process.env.CORTEX_PREVIEW_STATE || "/tmp/symx-cortex-preview.json", "utf8"));
  if (!/^mongodb:\/\/(127\.0\.0\.1|localhost):/.test(state.uri) || !state.uri.includes("/symx-cortex-disposable")) throw Error("Refusing non-disposable preview");
  browser = await chromium.launch({ executablePath: process.env.CORTEX_CHROMIUM_EXECUTABLE || undefined, headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport: { width: 1512, height: 1080 } });
  const login = await context.request.post("http://127.0.0.1:3000/api/auth/login", { data: { email: state.email, password: state.password } });
  if (!login.ok()) throw Error("Preview login failed");
  const stored = await (await context.request.get("http://127.0.0.1:3000/api/cortex")).json();
  if (stored.routes.find(r => r.routeCode === "CX800")?.deliveryEvents?.length !== 25) throw Error("MV3 stop timeline did not survive ingest/readback");
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("http://127.0.0.1:3000/cortex?demo=1");
  await page.waitForFunction(() => !!navigator.serviceWorker.controller, undefined, { timeout: 30000 });
  await page.waitForLoadState("networkidle", { timeout: 30000 });
  await expect(page.locator("tbody tr")).toHaveCount(15, { timeout: 15000 });
  await page.getByLabel("Filter station").selectOption("DFO2");
  await expect(page.locator("tbody tr")).toHaveCount(5);
  const attention = page.getByRole("region", { name: "DFO2 driver attention" });
  await expect(attention.getByRole("article")).toHaveCount(3);
  await expect(attention).toContainText("Check-in");
  await page.screenshot({ path: "artifacts/cortex-intelligence-desktop.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Review driver CX101", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("Recent pace has slowed");
  await expect(dialog).toContainText("10.0 /h");
  await expect(dialog).toContainText("Observed evidence:");
  await expect(dialog).toContainText("Questions for dispatch");
  await expect(dialog).toContainText("Possible explanations to verify");
  await expect(dialog).toContainText("3 prior observed workdays");
  await expect(dialog).toContainText("Recurring observation: pace slowdown on 3 captured days");
  await page.screenshot({ path: "artifacts/cortex-driver-detail.png", fullPage: true, animations: "disabled" });
  await dialog.getByRole("heading", { name: "Captured driver history", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "artifacts/cortex-driver-history.png", fullPage: true, animations: "disabled" });
  await dialog.getByRole("button", { name: "Close", exact: true }).first().click();
  await page.getByRole("button", { name: /^Open details for CX101,/ }).hover();
  await expect(page.getByRole("tooltip").filter({ hasText: "CX101" })).toBeVisible();
  // Exercise a real refresh while a dispatcher opens the still-visible route.
  await page.route("**/api/cortex?*", async route => {
    await new Promise(resolve => setTimeout(resolve, 1000));
    await route.continue();
  });
  const refreshed = page.waitForResponse(r => r.url().includes("/api/cortex?") && r.ok());
  await page.getByRole("button", { name: "Refresh", exact: true }).click();
  await page.getByRole("button", { name: /^Open details for CX102,/ }).click();
  await refreshed;
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText("Delivery gap: 35 min");
  await expect(dialog).toContainText("recent delivery event");
  await expect(dialog).toContainText("When safely stopped");
  await dialog.getByRole("button", { name: "Close", exact: true }).first().click();
  await page.getByLabel("Filter station").selectOption("DXC8");
  await expect(attention.getByRole("article")).toHaveCount(0);
  await page.getByLabel("Filter station").selectOption("DFO2");
  await page.setViewportSize({ width: 390, height: 844 });
  await attention.screenshot({ path: "artifacts/cortex-intelligence-mobile.png", animations: "disabled" });
  if (errors.length) throw Error(errors.join("\n"));
  await browser.close();
  console.log("PASS: driver intelligence preview, DFO2 attention, recent/earlier pace, gap suppression, evidence vs hypotheses, recurring history, preserved hover/dialog through refresh, mobile UI, MV3 numeric event readback; no browser errors.");
})().catch(async e => {
  console.error(e.message);
  if (browser) await browser.close();
  process.exitCode = 1;
});
